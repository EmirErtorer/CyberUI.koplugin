-- The gigs and eddies switch used for real: cancelling the three questions
-- keeps it on, answering all three turns it off (no money tiles, the Gigs tile
-- becomes the shop, every look can be worn), and turning it back on returns
-- a look that was not bought to the free one.
-- Run: E2E_NO_DIR=1 HOME_SETUP=tests/e2e/setup_home.py tests/e2e/run.sh tests/e2e/economy.lua <out>
local H = ...
local Economy = require("cyberui/data/economy")
local Ledger = require("cyberui/data/ledger")
local Settings = require("cyberui/settings")
local Shop = require("cyberui/data/shop")

-- Tap the switch in the settings row with this label.
local function flip()
    local row = H.find("Gigs and eddies", nil, false)
    H.check(row ~= nil, "the settings row is there")
    local w = require("device").screen:getWidth()
    H.tapAt(w - 60, row.y + row.h / 2)
end

H.step(4, function()
    Settings.set("gigs", nil)
    Settings.set("gigs_on", nil)
    for _i, cat in ipairs(Shop.categories) do Settings.set("style_" .. cat.id, nil) end
    Ledger.reload()
    Ledger.add("m", "/earned", 1, 300)
    Ledger.save()
    H.app().go("settings")
end)
H.step(2, function()
    H.app().current().section = "home"
    H.app().update()
end)
H.step(2, function()
    H.shot("economy-1-settings")
    flip()
end)
H.step(2, function()
    H.check(H.find("HOLD UP, CHOOM") ~= nil, "turning it off asks first")
    H.shot("economy-2-first")
    H.tap("KEEP IT")
end)
H.step(2, function()
    H.check(Economy.on(), "keeping it leaves the economy on")
    flip()
end)
H.step(2, function()
    H.tap("ZERO IT")
end)
H.step(2, function()
    H.check(H.find("FLATLINING THE ECONOMY?") ~= nil and Economy.on(), "a second question follows, still on")
    H.shot("economy-3-second")
    H.tap("FLATLINE IT")
end)
H.step(2, function()
    H.check(H.find("LAST CALL, RUNNER") ~= nil and Economy.on(), "and a third, still on")
    H.shot("economy-4-third")
    H.tap("ZERO IT FOR REAL")
end)
H.step(2, function()
    H.check(not Economy.on(), "the third yes turns it off")
    H.shot("economy-5-off")
    H.app().go("home")
end)
H.step(3, function()
    H.check(H.find("ALL LOOKS UNLOCKED") ~= nil and H.find("BACKLOG CLEAR") == nil, "the Gigs tile on home is the shop now")
    H.tap("ALL LOOKS UNLOCKED")
end)
H.step(2, function()
    H.check(H.app().current().id == "shop" and H.find("SHOP // GIGS OFF") ~= nil, "it opens the shop, marked as off")
    H.check(H.find("ON LOAN", nil, true) ~= nil, "looks not bought say they are on loan")
    H.shot("economy-6-shop")
    H.tap("ON LOAN")
end)
H.step(2, function()
    H.check(Shop.worn("frame").id ~= "frame.standard", "a borrowed look can be worn")
    H.shot("economy-7-worn")
    H.app().go("settings")
end)
H.step(2, function()
    H.app().current().section = "home"
    H.app().update()
end)
H.step(2, function()
    flip()
end)
H.step(2, function()
    H.check(Economy.on() and Shop.worn("frame").id == "frame.standard" and Settings.get("style_frame") == nil,
        "turning it on needs no questions and puts the borrowed look back to the free one")
    H.shot("economy-8-back-on")
    Settings.set("gigs_on", nil)
    Settings.set("gigs", nil)
    for _i, cat in ipairs(Shop.categories) do Settings.set("style_" .. cat.id, nil) end
end)
