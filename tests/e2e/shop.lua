-- The shop used for real: eddies in the signed ledger, a style previewed and
-- bought with a tap, worn, shown on the ID card, and a jack-in card in a
-- bought style. Needs setup_home.py.
local H = ...
local Ledger = require("cyberui/data/ledger")
local Settings = require("cyberui/settings")
local Shop = require("cyberui/data/shop")

local function app() return H.app() end
local function screen() return H.app().current() end

H.step(1, function()
    Settings.set("gigs", nil)
    Settings.set("style_frame", nil)
    Settings.set("style_jackin", nil)
    Ledger.reload()
    Ledger.add("m", "/earned", 1, 400)
    Ledger.save()
    app().push("gigs")
end)
H.step(1, function()
    H.tap("SHOP")
end)
H.step(1, function()
    H.check(screen().id == "shop", "the Gigs screen opens the shop")
    H.check(H.find("SHOP // BALANCE €$400") ~= nil, "the balance shows on the shop")
    H.shot("shop1-frames")
    H.tap("€$100")
end)
H.step(1, function()
    H.check(app().overlay() ~= nil and H.find("BUY €$100") ~= nil, "an unowned style opens a preview with its price")
    H.shot("shop2-preview")
    H.tap("BUY €$100")
end)
H.step(1, function()
    H.check(Shop.owned(Shop.style("frame.notch")) and Shop.worn("frame").id == "frame.notch", "buying owns the style and wears it")
    H.check(Ledger.balance() == 300, "the price was taken from the balance")
    H.shot("shop3-bought")
    H.tap("Jack-ins")
end)
H.step(1, function()
    H.shot("shop4-jackins")
    require("cyberui/profileflow").card()
end)
H.step(1, function()
    H.check(H.find("EDDIES") ~= nil, "the ID card shows in the worn frame")
    H.shot("shop5-card")
    app().closeDialog()
    Shop.wear(Shop.style("jackin.standard"))
    local ok = Shop.buy(Shop.style("jackin.terminal"))
    H.check(ok and Shop.wear(Shop.style("jackin.terminal")), "a jack-in style is bought and worn")
    app().flash(require("cyberui/jackin").card(require("cyberui/data/library").all()[1]))
    H.shot("shop6-jackin-worn")
    app().update()
end)
