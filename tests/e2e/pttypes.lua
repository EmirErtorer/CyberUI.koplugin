-- A Portuguese reader's session: rename a collection with accented capitals and a
-- locked Shift, edit a book's details from its dossier, and group the library by genre.
local H = ...
local S = 1
local Collections = require("cyberui/data/collections")
local Metadata = require("cyberui/data/metadata")
local Books = require("cyberui/data/books")
local Library = require("cyberui/data/library")
local Settings = require("cyberui/settings")
local all, book

H.step(1, function()
    all = Library.all()
    book = all[1]
    Collections.create("Fantasia")
    H.app().push("collections")
end)
H.step(S, function()
    H.shot("1-collections")
    H.hold("Fantasia")
end)
H.step(S, function()
    H.shot("2-collection-hold-sheet")
    H.check(H.find("Rename") ~= nil, "the hold sheet offers Rename")
    H.tap("Rename")
end)
H.step(S, function()
    H.check(H.typed() == "Fantasia", "the input starts with the current name")
    H.shot("3-rename-input")
    for _i = 1, 8 do H.tap(nil, "backspace") end
end)
H.step(S, function()
    H.check(H.typed() == "", "the name was cleared")
    H.tap("áãç")
end)
H.step(S, function()
    H.shot("4-accent-layer")
    H.check(H.find("á", nil, true) ~= nil and H.find("ã", nil, true) ~= nil, "á and ã are on the accented layer")
    H.tap("⇧")
end)
H.step(S, function()
    H.shot("5-accent-capitals")
    H.check(H.find("Á", nil, true) ~= nil and H.find("Ã", nil, true) ~= nil, "Shift gives Á and Ã")
    H.tap("É")
end)
H.step(S, function()
    H.check(H.typed() == "É", "É was typed")
    -- one-shot Shift is spent: back to the letters, then lock Shift with a double tap
    H.tap("abc")
end)
H.step(S, function()
    for _i, ch in ipairs({ "p", "i", "c", "o", "s" }) do H.tap(ch) end
    H.check(H.typed() == "Épicos", "the rest is lower case after one capital")
    H.tap("⇧")
end)
H.step(S, function() H.tap("⇧") end)
H.step(S, function()
    H.shot("6-shift-locked")
    H.check(H.find("⇧⇧", nil, true) ~= nil, "a second tap locks Shift")
    for _i, ch in ipairs({ "X", "Y" }) do H.tap(ch) end
    H.check(H.typed() == "ÉpicosXY", "a locked Shift keeps capitals coming")
    H.tap("áãç")
end)
H.step(S, function()
    H.shot("7-locked-on-accents")
    H.check(H.find("Ã", nil, true) ~= nil, "the lock follows to the accented layer")
    H.tap("Ã")
    H.check(H.typed() == "ÉpicosXYÃ", "accented capital typed under the lock")
    for _i = 1, 3 do H.tap(nil, "backspace") end
    H.check(H.typed() == "Épicos", "backspace removes whole accented letters")
end)
H.step(S, function()
    H.tap("Rename")
end)
H.step(1.5, function()
    local names = {}
    for _i, c in ipairs(Collections.list()) do names[c.name] = true end
    H.check(names["Épicos"] and not names["Fantasia"], "the collection was renamed")
    H.check(H.find("Épicos") ~= nil, "the card shows the new name")
    H.shot("8-collection-renamed")
end)

-- details of a book
H.step(1, function()
    Collections.remove("Épicos")
    H.app().push("dossier", { path = book })
end)
H.step(S, function()
    H.shot("9-dossier")
    H.check(H.find("EDIT INFO", nil, true) ~= nil, "the dossier has EDIT INFO")
    H.tap("EDIT INFO")
end)
H.step(S, function()
    H.shot("10-edit-details")
    H.check(H.find("TITLE", nil, true) ~= nil and H.find("GENRES", nil, true) ~= nil, "the editor lists the details")
    H.tap("TITLE")
end)
H.step(S, function()
    H.tap(nil, "backspace")   -- cursor is at the end of the old title
    H.check(H.typed() ~= nil, "the title opens in the keyboard")
    H.shot("11-title-input")
    for _i = 1, 200 do H.tap(nil, "backspace") end
end)
H.step(S, function()
    H.typeKeys("O Senhor", nil)
    H.check(H.typed() == "O Senhor", "a new title is typed, got " .. tostring(H.typed()))
    H.tap("Save")
end)
H.step(1.5, function()
    H.check(Books.info(book).title == "O Senhor" and Metadata.changed(book, "title"), "the title is saved as custom metadata")
    H.check(H.find("EDITED") ~= nil, "the row is marked EDITED")
    H.tap("GENRES")
end)
H.step(S, function()
    for _i = 1, 200 do H.tap(nil, "backspace") end
end)
H.step(S, function()
    H.typeKeys("Fantasia", nil)
    H.tap("Save")
end)
H.step(1.5, function()
    H.check(Books.info(book).genres[1] == "Fantasia", "the genre is saved")
    H.tap("SERIES NUMBER")
end)
H.step(S, function()
    for _i = 1, 10 do H.tap(nil, "backspace") end
    H.tap("?123")
end)
H.step(S, function()
    H.tap("4")
    H.tap("Save")
end)
H.step(1.5, function()
    H.check(Books.info(book).series_index == 4, "the series number is saved")
    H.shot("12-edited-details")
    H.hold("TITLE")
end)
H.step(1.5, function()
    H.check(not Metadata.changed(book, "title"), "holding a detail brings the book's own back")
    H.shot("13-title-restored")
    H.tap("DONE")
end)

-- the hold sheet of a book has it too
H.step(1, function()
    require("cyberui/actions").bookSheet(book)
end)
H.step(S, function()
    H.shot("13b-book-hold-sheet")
    H.check(H.find("Edit info") ~= nil, "the book's hold sheet offers Edit info")
    H.tap("Edit info")
end)
H.step(S, function()
    H.check(H.find("GENRES", nil, true) ~= nil, "it opens the editor")
    H.app().back()
end)

-- genre grouping
H.step(1.5, function()
    for i = 2, math.min(4, #all) do Metadata.set(all[i], "keywords", i == 2 and "Fantasia\nÉpico" or "Clássicos") end
    Settings.set("library_group", "genre")
    Settings.flush()
    H.app().go("library")
end)
H.step(2, function()
    H.shot("14-library-by-genre")
    H.check(H.find("Fantasia", nil, true) ~= nil, "the Genre grouping lists the genres")
    H.tap("Fantasia")
end)
H.step(2, function()
    H.shot("15-genre-books")
    local lib = H.app().current()
    local n = 0
    for _i, it in ipairs(lib.items or {}) do if it.path then n = n + 1 end end
    H.check(n == 2, "the genre holds its two books")
end)

-- put it all back
H.step(1, function()
    for _i, p in ipairs(all) do Metadata.reset(p) end
    Settings.set("library_group", nil)
    Settings.flush()
end)
